public class Lab2Q3 {
    public static void main(String[] args) {

        // Given sides
        double sideA = 3;
        double sideB = 4;

        // Calculate hypotenuse
        double hypotenuse = Math.sqrt((sideA * sideA) + (sideB * sideB));

        // Display result
        System.out.println("Length of the hypotenuse = " + hypotenuse);
    }
}